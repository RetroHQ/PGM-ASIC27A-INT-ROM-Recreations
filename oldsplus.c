void CommandHandler(u32 latch)
{
	u16 latchLow = (u16) latch;

	switch ((latch >> 16) & 0xff)
	{
		case 0x88:
			gValueKey = 0x100;
			WriteLatch(0x00990000 | (REGIONSHARE << 8));
			break;

		case 0xd0:
			WriteLatch(0xa01000 + (latchLow << 5));
			break;

		case 0xc0:
			WriteLatch(0xa00000 + (latchLow << 6));
			break;

		case 0xc3:
			WriteLatch(0xa00800 + (latchLow << 6));
			break;

		case 0x36:
			m_extra_ram[1] = latchLow;
			WriteLatch(0x990000);
			break;

		case 0x33:
			m_extra_ram[0] = latchLow;
			WriteLatch(0x990000);
			break;

		case 0x35:
			m_extra_ram[1] += latchLow;
			WriteLatch(0x990000);
			break;

		case 0x37:
			m_extra_ram[0] += latchLow;
			WriteLatch(0x990000);
			break;

		case 0x34:
			WriteLatch(m_extra_ram[1]);
			break;

		case 0x38:
			WriteLatch(m_extra_ram[0]);
			break;

		case 0x80:
			WriteLatch(oldsplus_80[latchLow]);
			break;

		case 0xe7:
			m_extra_ram[3] = latchLow;
			WriteLatch(0x990000);
			break;

		case 0xe5:
			switch (m_extra_ram[3])
			{
				case 0xb000:
					m_slots[0xb] = latchLow;
					m_slots[0xc] = 0;
					break;

				case 0xc000:
					m_slots[0xc] = latchLow;
					break;

				case 0xd000:
					m_slots[0xd] = latchLow;
					break;

				case 0xf000:
					m_slots[0xf] = latchLow;
					break;
			}
			WriteLatch(0x990000);
			break;

		case 0xf8:
			WriteLatch(m_slots[latchLow]);
			break;

		case 0xfc:
			WriteLatch(oldsplus_fc[latchLow]);
			break;

		case 0xc5:
			m_slots[0xd]--;
			WriteLatch(0x990000);
			break;

		case 0xd6:
			m_slots[0xb]++;
			WriteLatch(0x990000);
			break;

		case 0x3a:
			m_slots[0xf] = 0;
			WriteLatch(0x990000);
			break;

		case 0xf0:
			m_extra_ram[4] = latchLow;
			WriteLatch(0x990000);
			break;

		case 0xed:
			WriteLatch(0x900000 + (((latchLow << 0x6) + m_extra_ram[4]) << 2));
			break;

		case 0xe0:
			m_extra_ram[2] = latchLow;
			WriteLatch(0x990000);
			break;

		case 0xdc:
			WriteLatch(0x904000 + (((latchLow << 0x6) + m_extra_ram[2]) << 2));
			break;

		case 0xcb:
			WriteLatch(0xc000);
			break;

		case 0xa0:
			WriteLatch(oldsplus_a0[latchLow]);
			break;

		case 0xba:
			WriteLatch(oldsplus_ba[latchLow]);
			break;

		case 0x5e:
			WriteLatch(oldsplus_5e[latchLow]);
			break;

		case 0xb0:
			WriteLatch(oldsplus_b0[latchLow]);
			break;

		case 0xae:
			WriteLatch(oldsplus_ae[latchLow]);
			break;

		case 0x9d:
			WriteLatch(oldsplus_9d[latchLow]);
			break;

		case 0x90:
			WriteLatch(oldsplus_90[latchLow]);
			break;

		case 0x8c:
			WriteLatch(oldsplus_8c[latchLow]);
			break;

		default:
			WriteLatch(0x990000);
			//printf("%06X: oldsplus_UNKNOWN W CMD %X  VAL %X\n", pc,m_value1,latchLow);
			break;
	}
}
