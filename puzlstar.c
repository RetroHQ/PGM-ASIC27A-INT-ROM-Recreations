void CommandHandler(u32 latch)
{
	u16 latchLow = (u16) latch;

	switch ((latch >> 16) & 0xff)
	{
		case 0x99:
			gValueKey = 0x100;
			WriteLatch(0x00880000 | (REGIONSHARE << 8));
			break;

		case 0xe0:
			WriteLatch(0xa00000 + (latchLow << 6));
			break;

		case 0xdc:
			WriteLatch(0xa00800 + (latchLow << 6));
			break;

		case 0xd0:
			WriteLatch(0xa01000 + (latchLow << 5));
			break;

		case 0xb1:
			m_pstar_b1_value = latchLow;
			WriteLatch(0x890000);
			break;

		case 0xbf:
			WriteLatch(m_pstar_b1_value * latchLow);
			break;

		case 0xc1: //TODO:TIMER  0,1,2,FIX TO 0 should be OK?
			WriteLatch(0);
			break;

		case 0xce: //TODO:TIMER  0,1,2
			//m_pstar_ce_value = latchLow;
			WriteLatch(0x890000);
			break;

		case 0xcf: //TODO:TIMER  0,1,2
			//m_extra_ram[m_pstar_ce_value] = latchLow;
			WriteLatch(0x890000);
			break;

		case 0xe7:
			m_curslot = (latchLow >> 12) & 0xf;
			m_slots[m_curslot] &= 0xffff;
			m_slots[m_curslot] |= (latchLow & 0xff) << 16;
			WriteLatch(0x890000);
			break;

		case 0xe5:
			m_slots[m_curslot] &= 0xff0000;
			m_slots[m_curslot] |= latchLow;
			WriteLatch(0x890000);
			break;

		case 0xf8: //@73C
			WriteLatch(m_slots[latchLow & 0xf] & 0xffffff);
			break;

		case 0xba:
			WriteLatch(pstar_ba[latchLow]);
			break;

		case 0xb0:
			WriteLatch(pstar_b0[latchLow]);
			break;

		case 0xae:
			WriteLatch(pstar_ae[latchLow]);
			break;

		case 0xa0:
			WriteLatch(pstar_a0[latchLow]);
			break;

		case 0x9d:
			WriteLatch(pstar_9d[latchLow]);
			break;

		case 0x90:
			WriteLatch(pstar_90[latchLow]);
			break;

		case 0x8c:
			WriteLatch(pstar_8c[latchLow]);
			break;

		case 0x80:
			WriteLatch(pstar_80[latchLow]);
			break;

		default:
			WriteLatch(0x890000);
		//	logerror("PSTARS PC(%06x) UNKNOWN %4X %4X\n", pc, m_value1, latchLow);
			break;
	}
}
